-- Deploy odo:012_notify_template_history to pg
-- requires: 001_odo_baseline

-- Keep every version of every notification template, so a bad edit can
-- be seen and undone (odo-notify template/versions, template/version,
-- template/restore; the admin UI's template History page).
--
-- A trigger records the versions rather than odo-notify, so nothing that
-- writes a template can skip it: the admin API, app registration, and
-- direct SQL all leave a version. Writers that know who is acting say so
-- with transaction-local settings, read here:
--
--   app.actor_id       auth.usr id of the person making the change
--   app.restored_from  version number being restored (marks a restore)
--
-- Unset, a version records no author (an INSERT falls back to the
-- template's created_by). An UPDATE that changes nothing but updated_at
-- isn't a version.
--
-- Versions are append-only: updates are refused, and deletes need the
-- same explicit app.allow_hard_delete override as the rest of the schema.
-- Existing templates get a 'baseline' version holding their current
-- content, since what came before was never kept.

BEGIN;

CREATE TABLE notification.template_version (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template integer NOT NULL REFERENCES notification.template(id),
    version integer NOT NULL,
    action text NOT NULL
        CHECK (action IN ('baseline', 'create', 'update', 'restore', 'delete')),
    restored_from integer,
    code character varying(100) NOT NULL,
    name character varying(255) NOT NULL,
    description text,
    org_unit integer NOT NULL,
    subject_template text NOT NULL,
    body_template text NOT NULL,
    body_template_html text,
    sample_data jsonb,
    is_active boolean NOT NULL,
    deleted_at timestamp with time zone,
    changed_by integer REFERENCES auth.usr(id),
    changed_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT template_version_template_version_key UNIQUE (template, version),
    CONSTRAINT template_version_restored_from_check
        CHECK ((action = 'restore') = (restored_from IS NOT NULL))
);

COMMENT ON TABLE notification.template_version IS
    'Every version of every notification template, written by trigger; append-only';

INSERT INTO notification.template_version (
    template, version, action, code, name, description, org_unit,
    subject_template, body_template, body_template_html, sample_data,
    is_active, deleted_at, changed_at)
SELECT id, 1, 'baseline', code, name, description, org_unit,
       subject_template, body_template, body_template_html, sample_data,
       is_active, deleted_at, updated_at
  FROM notification.template;

CREATE FUNCTION notification.record_template_version() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
DECLARE
    v_actor integer := NULLIF(current_setting('app.actor_id', true), '')::integer;
    v_restored integer := NULLIF(current_setting('app.restored_from', true), '')::integer;
    v_action text;
BEGIN
    IF TG_OP = 'INSERT' THEN
        v_action := 'create';
        v_actor := COALESCE(v_actor, NEW.created_by);
        v_restored := NULL;
    ELSIF (OLD.code, OLD.name, OLD.description, OLD.org_unit,
           OLD.subject_template, OLD.body_template, OLD.body_template_html,
           OLD.sample_data, OLD.is_active, OLD.deleted_at)
          IS NOT DISTINCT FROM
          (NEW.code, NEW.name, NEW.description, NEW.org_unit,
           NEW.subject_template, NEW.body_template, NEW.body_template_html,
           NEW.sample_data, NEW.is_active, NEW.deleted_at) THEN
        RETURN NULL;
    ELSIF OLD.deleted_at IS NULL AND NEW.deleted_at IS NOT NULL THEN
        v_action := 'delete';
        v_restored := NULL;
    ELSIF v_restored IS NOT NULL THEN
        v_action := 'restore';
    ELSE
        v_action := 'update';
    END IF;

    -- The UPDATE holds the template's row lock, so concurrent writers
    -- can't both take the same next version number.
    INSERT INTO notification.template_version (
        template, version, action, restored_from, code, name, description,
        org_unit, subject_template, body_template, body_template_html,
        sample_data, is_active, deleted_at, changed_by)
    VALUES (
        NEW.id,
        COALESCE((SELECT max(version) FROM notification.template_version
                   WHERE template = NEW.id), 0) + 1,
        v_action, v_restored, NEW.code, NEW.name, NEW.description,
        NEW.org_unit, NEW.subject_template, NEW.body_template,
        NEW.body_template_html, NEW.sample_data, NEW.is_active,
        NEW.deleted_at, v_actor);
    RETURN NULL;
END;
$$;

CREATE TRIGGER record_template_version
    AFTER INSERT OR UPDATE ON notification.template
    FOR EACH ROW EXECUTE FUNCTION notification.record_template_version();

CREATE FUNCTION notification.refuse_template_version_update() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    RAISE EXCEPTION 'notification.template_version is append-only'
        USING errcode = 'restrict_violation';
END;
$$;

CREATE TRIGGER refuse_update
    BEFORE UPDATE ON notification.template_version
    FOR EACH ROW EXECUTE FUNCTION notification.refuse_template_version_update();

CREATE TRIGGER prevent_hard_delete
    BEFORE DELETE ON notification.template_version
    FOR EACH ROW EXECUTE FUNCTION audit.prevent_hard_delete();

COMMIT;
